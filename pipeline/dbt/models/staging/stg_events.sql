SELECT
  run_id,
  event_id,
  event_type,
  SAFE_CAST(event_ts AS TIMESTAMP) AS event_ts,
  is_synthetic,
  region_key,
  band_id,
  source,
  SAFE_CAST(source_accessed_at AS TIMESTAMP) AS source_accessed_at,
  COALESCE(JSON_VALUE_ARRAY(raw_payload, '$.dirty_flags'), ARRAY<STRING>[]) AS dirty_flags,
  raw_payload,
  ingested_at,
  JSON_VALUE(raw_payload, '$.session_id') AS session_id,
  JSON_VALUE(raw_payload, '$.event_name') AS event_name,
  JSON_VALUE(raw_payload, '$.endpoint') AS endpoint,
  JSON_VALUE(raw_payload, '$.target') AS target,
  SAFE_CAST(JSON_VALUE(raw_payload, '$.latency_ms') AS INT64) AS raw_latency_ms,
  SAFE_CAST(JSON_VALUE(raw_payload, '$.http_status') AS INT64) AS raw_http_status,
  JSON_VALUE(raw_payload, '$.obs_id') AS obs_id,
  SAFE_CAST(JSON_VALUE(raw_payload, '$.observation.em_min') AS FLOAT64) AS em_min_m,
  SAFE_CAST(JSON_VALUE(raw_payload, '$.observation.em_max') AS FLOAT64) AS em_max_m,
  SAFE_CAST(JSON_VALUE(raw_payload, '$.observation.s_ra') AS FLOAT64) AS s_ra_deg,
  SAFE_CAST(JSON_VALUE(raw_payload, '$.observation.s_dec') AS FLOAT64) AS s_dec_deg,
  SAFE_CAST(JSON_VALUE(raw_payload, '$.observation.t_min_mjd') AS FLOAT64) AS t_min_mjd,
  SAFE_CAST(JSON_VALUE(raw_payload, '$.observation.observation_time') AS TIMESTAMP) AS observation_time,
  JSON_VALUE(raw_payload, '$.observation.calib_level') AS calib_level,
  JSON_VALUE(raw_payload, '$.observation.access_url') AS access_url,
  JSON_VALUE(raw_payload, '$.observation.obs_collection') AS obs_collection,
  SAFE_CAST(JSON_VALUE(raw_payload, '$.metadata_is_synthetic') AS BOOL) AS metadata_is_synthetic,
  SAFE_CAST(JSON_VALUE(raw_payload, '$.quality_metrics_synthetic') AS BOOL) AS quality_metrics_synthetic,
  JSON_VALUE(raw_payload, '$.quality_metrics.background_level') AS raw_background_level,
  JSON_VALUE(raw_payload, '$.quality_metrics.noise_sigma') AS raw_noise_sigma,
  JSON_VALUE(raw_payload, '$.quality_metrics.saturated_pixel_fraction') AS raw_saturated_pixel_fraction,
  JSON_VALUE(raw_payload, '$.quality_metrics.pointing_error_arcsec') AS raw_pointing_error_arcsec,
  JSON_VALUE(raw_payload, '$.quality_metrics.processing_latency_ms') AS raw_processing_latency_ms
FROM {{ source('raw', 'events') }}
